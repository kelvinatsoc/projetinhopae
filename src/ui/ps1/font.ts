/** Bits de cada glifo (linha a linha, 5 bits por linha). */
const BITS: Record<string, number[]> = {};
for (const [ch, rows] of Object.entries(G)) BITS[ch] = rows.split("|").map((r) => [...r].reduce((a, c) => (a << 1) | (c === "#" ? 1 : 0), 0));

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function glyph(ch: string): number[] {
  return BITS[ch] ?? BITS[ch.toUpperCase()] ?? BITS[" "];
}

/** Largura do texto em pixels (escala 1), com 1 px entre letras. */
export function textWidth(text: string, scale = 1): number {
  return text.length ? (text.length * (GLYPH_W + 1) - 1) * scale : 0;
}

/** Escreve o texto no canvas com retângulos (nada de fillText: fica nítido e sem antisserrilhado). */
export function drawText(g: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1, shadow?: string) {
  if (shadow) drawText(g, text, x + scale, y + scale, shadow, scale);
  g.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text) {
    const rows = glyph(ch);
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r];
      if (!bits) continue;
      for (let c = 0; c < GLYPH_W; c++) if (bits & (1 << (GLYPH_W - 1 - c))) g.fillRect(cx + c * scale, cy + r * scale, scale, scale);
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
